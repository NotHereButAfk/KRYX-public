export function setMarketPreview(button, modelSrc, skin) {
  button.type = 'button';
  button.setAttribute('aria-label', `Inspect ${skin.name} model`);
  const image = new Image();
  image.alt = skin.name; image.decoding = 'async';
  const cardSrc = THEMED_SKIN_CARDS[skin.id];
  const sword = skin.weaponId === 'sword';
  image.classList.toggle('upright-sword-preview', sword && !cardSrc);
  button.classList.toggle('shop-preview-card', !!cardSrc);
  image.src = cardSrc || modelSrc;
  image.onerror = () => { image.onerror = null; button.classList.remove('shop-preview-card'); image.src = modelSrc; };
  button.replaceChildren(image);
  button.onclick = () => {
    const dialog = document.createElement('dialog'); dialog.className = 'market-image-dialog';
    const close = document.createElement('button'); close.type = 'button'; close.textContent = 'Close ×';
    const title = document.createElement('h2'); title.textContent = skin.name;
    const detail = document.createElement('p'); detail.textContent = `${skin.rarity.toUpperCase()} · ACTUAL GAME MODEL`;
    const full = new Image(); full.src = modelSrc; full.alt = skin.name;
    dialog.append(close, full, title, detail);
    close.onclick = () => dialog.close();
    dialog.onclick = e => { if (e.target === dialog) dialog.close(); };
    dialog.addEventListener('keydown', e => e.stopPropagation());
    dialog.addEventListener('close', () => { dialog.remove(); button.focus({ preventScroll: true }); }, { once: true });
    document.body.append(dialog); dialog.showModal();
  };
}
