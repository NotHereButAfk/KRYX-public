import assert from 'node:assert/strict';
import { buildLeaderboardRows, buildMatchRows, compareMatchRows } from '../src/core/MatchRows.js';
const rows=[{name:'Rich',kills:2,score:9999},{name:'Leader',kills:10,score:10},{name:'Tie',kills:10,score:5},{name:'Zero',kills:0,score:50000}];
assert.deepEqual(buildLeaderboardRows(rows).map(r=>r.name),['Leader','Tie','Rich','Zero']);
assert.equal(rows[0].name,'Rich','do not mutate final server snapshot');
const live=buildMatchRows({authClient:{you:2,self:rows[1],roster:rows.map((r,i)=>({...r,id:i+1}))}});
assert.equal(live[0].name,'Leader');
assert(compareMatchRows({name:'A',kills:20,score:0},{name:'B',kills:19,score:999999})<0);
assert.deepEqual(buildLeaderboardRows([{name:'Missing'},...rows]).map(r=>r.name),['Leader','Tie','Rich','Zero','Missing']);
console.log('Leaderboard passed: higher kills always rank first in live/final results; score only breaks equal-kill ordering.');
import { AuthRoom } from '../server/authroom.mjs';
const room = new AuthRoom(undefined, {targetPopulation:0});
const a=room.add(()=>{},'MostKills'), b=room.add(()=>{},'MostScore');
Object.assign(room.players.get(a),{kills:10,score:10,accountId:'a'});
Object.assign(room.players.get(b),{kills:2,score:9999,accountId:'b'});
const wins=[];let paid=[];
room.achievements={record:(id,stats)=>{if(stats.wins)wins.push(id);}};
room.economy={ready:true,finish:async ids=>{paid=ids;}};
room._rotateMatch(room.matchStart+room.matchDurationMs+1);
assert.deepEqual(wins,['a']);
assert.deepEqual(paid,[a]);
console.log('Server victory passed: achievements and winner selection follow kills, not currency/score.');
