import assert from 'node:assert/strict';
import {AuthRoom} from '../server/authroom.mjs';
import {AUTHORITY_TEST_ARENA} from './fixtures/authorityArena.mjs';
const room=new AuthRoom(AUTHORITY_TEST_ARENA,{targetPopulation:3});
const id=room.add(()=>{},'Watcher'),p=room.players.get(id);
room._rotateMatch=()=>false;
const originalHealth=p.health,originalScore=p.score;
room.setSpectating(id,true);
assert.equal([...room.players.values()].filter(p=>p.isBot).length,3,'observer displaced an active bot');
const position=[p.state.px,p.state.py,p.state.pz];
room.onInput(id,{seq:1,mz:1,mx:0,yaw:0,sprint:true});
room.onFire(id,{seq:1,wid:'m4',yaw:0,pitch:0});
for(let i=0;i<60;i++)room.update();
assert.deepEqual([p.state.px,p.state.py,p.state.pz],position,'spectator moved through gameplay');
assert.equal(p.health,originalHealth,'spectator took damage');
assert.equal(p.score,originalScore,'spectator gained score');
assert.equal(room._canSimulate(p),false);
p.mapReady=false;room._roundWaiting=true;room._readyDeadline=Date.now()+10000;
room._advanceRoundGate();assert.equal(room._roundWaiting,false,'observer held up spawn gate');
p.mapReady=true;room.setSpectating(id,false);
assert(room._canSimulate(p),'joining did not restore gameplay');
assert.equal(p.health,originalHealth,'joining changed health');
assert.equal([...room.players.values()].filter(p=>p.isBot).length,2,'Join did not reclaim an active slot');
console.log('Spectator authority passed: no movement, combat, score or ready-gate participation; Join restores the slot without healing.');

const full = new AuthRoom(AUTHORITY_TEST_ARENA,{targetPopulation:1});
const watcher = full.add(()=>{},'Watcher');full.setSpectating(watcher,true);
full.add(()=>{},'Active player');full.setSpectating(watcher,false);
assert(full.players.get(watcher).spectating,'spectator bypassed full room capacity');
console.log('Spectator Join respects active human capacity.');
