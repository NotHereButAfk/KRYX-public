import assert from 'node:assert/strict';
import {EconomyRuntime} from '../server/economy/runtime.mjs';
import {DEFAULT_ECONOMY} from '../server/economy/config.mjs';
const runtime = new EconomyRuntime({}, {clock:()=>100000});
runtime.config=structuredClone(DEFAULT_ECONOMY);
runtime.config.killRewards.botMin=runtime.config.killRewards.botMax='0.77';
runtime.match={id:'test', mode:'deathmatch', startedAt:0,config:runtime.config,players:{}};
runtime.ready=true;
await runtime.join('guest',null,()=>{});
runtime.activity('guest',true,50);
const reward=runtime.award('guest','kill',{victimIsBot:true});
assert.equal(reward.score,77);
assert.equal(reward.e,'0.0000');
assert.equal(reward.guest,true);
assert.equal(runtime.preview('guest').score,77);
assert.equal(runtime.preview('guest').balance,'0.0000');
assert.equal(runtime.preview('guest').finalE,'0.0000');
runtime.config.killRewards.playerMin=runtime.config.killRewards.playerMax='1.5';
assert.equal(runtime.award('guest','kill',{victimStreak:5}).score,450);
assert.equal(runtime.preview('guest').score,527);
assert.equal(runtime.award('guest','assist').score,10);
assert.equal(runtime.preview('guest').score,537);
assert.equal(runtime.participant('guest').actions.every(a=>!a.allowed),true);
const player=runtime.participant('guest');
player.userId='signed-in';
assert.equal(runtime.award('guest','kill',{victimIsBot:true}).score,100);
assert.equal(runtime.preview('guest').guest,false);
console.log('Guest reward conversion: 0.77 K = 77 points; streaks, assists, no guest currency, account behavior PASS');
