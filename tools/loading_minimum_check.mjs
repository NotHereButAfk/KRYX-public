import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {MIN_LOADING_MS,remainingLoadingMs} from '../src/core/LoadingTiming.js';
assert.equal(MIN_LOADING_MS,0);
assert.equal(remainingLoadingMs(100,100),0);
assert.equal(remainingLoadingMs(100,2600),0);
assert.equal(remainingLoadingMs(100,9100),0,'slow loading adds no extra delay');
const source=readFileSync(new URL('../src/core/Game.js',import.meta.url),'utf8');
const bridge=readFileSync(new URL('../src/net/AuthNetBridge.js',import.meta.url),'utf8');
const extract=(start,end)=>source.split(start)[1].split(end)[0].trim().replace(/}\s*$/,'');
const AsyncFunction=Object.getPrototypeOf(async function(){}).constructor;
let now=1000, waits=[], resume;
const wait=new AsyncFunction('remainingLoadingMs','performance','setTimeout',extract('  async _waitForMapLoadingMinimum() {','  async _finishMapLoading() {'));
const game={_mapLoadingSequence:1,_mapLoadingShownAt:0};
const pending=wait.call(game,()=>6000,{now:()=>now},(resolve,ms)=>{waits.push(ms);resume=resolve;});
assert.deepEqual(waits,[6000]);
game._mapLoadingSequence++;
resume();
assert.equal(await pending,false,'cancelled loader cannot finish a newer load');
now=9000;waits=[];
assert.equal(await wait.call(game,(started)=>remainingLoadingMs(started,now),{now:()=>now},()=>{throw Error('unnecessary delay')}),true);
assert.match(source,/await delay\(remainingLoadingMs\(startupShownAt\)\)/);
assert.match(source,/_finishMapLoading\(\)[\s\S]*?await this\._waitForMapLoadingMinimum\(\)[\s\S]*?classList.add\('ml-fade'\)/);
assert.match(bridge,/await game\._waitForMapLoadingMinimum\?\.\(\)[\s\S]*?this.client.sendReady\(\)/);
assert.match(bridge,/onMapChange[\s\S]*?await game\._waitForMapLoadingMinimum\?\.\(\)[\s\S]*?this.client.sendReady\(mapId, match.start\)/);
console.log('Loading readiness passed: no artificial delay for fast/slow loads; cancellation and multiplayer readiness retained.');
