import assert from 'node:assert/strict';
import * as THREE from 'three';
import {AuthRoom,TICK_HZ} from '../server/authroom.mjs';
import {GrenadeSystem} from '../src/weapons/GrenadeSystem.js';
import {consumeThrowable} from '../src/core/GameplayInput.js';
assert.equal(consumeThrowable({consumeJustPressed:key=>key==='KeyG'}),'smoke');
const room=new AuthRoom({id:'smoke-proof',half:50,boxes:[{min:[-5,0,-3],max:[5,5,-2.8]}],platforms:[],spawns:[[0,0,0]],pickups:[],gravLifts:[],teleporters:[]});
const p=room.players.get(room.add(()=>{},'Smoke test',false));
Object.assign(p.state,{px:0,py:0,pz:0});
room.onAbility(p.id,{seq:1,kind:'smoke',yaw:0,pitch:0});
room.update();
assert.equal(room.projectiles.length,1,'G must create a physical projectile');
assert.equal(room.smokes.length,0,'smoke must not appear instantly');
assert(!room.events.some(e=>e.e==='ability' && e.kind==='smoke'),'visual smoke must wait for fuse');
const grenade=room.projectiles[0];
assert.equal(grenade.kind,'smoke');
assert.equal(grenade.until-room.tick,Math.round(1.2*TICK_HZ));
const visuals=new GrenadeSystem(new THREE.Scene());
visuals.syncProjectiles([grenade]);
assert(visuals.projectileMeshes.get(grenade.id).isGroup,'remote smoke must use canister model, not rocket capsule');
let bounced=false;
while(room.tick<grenade.until){room.tick++;room._updateProjectiles();bounced ||= grenade.vz>0;}
assert(bounced,'smoke canister must bounce off the wall');
assert.equal(room.projectiles.length,0);
assert.equal(room.smokes.length,1);
assert.equal(room.smokes[0].z,grenade.z);
assert(room.smokes[0].z>-2.8,'smoke must remain on the near side of the wall');
assert.equal(room.events.filter(e=>e.e==='ability' && e.kind==='smoke').length,1);
assert.equal(p.health,100,'smoke must not deal frag damage');
visuals.syncProjectiles([]);assert.equal(visuals.projectileMeshes.size,0);
console.log('Smoke grenade passed: G input, real canister, wall bounce, delayed smoke at final position, no damage, cleanup');
