import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { makeAuthServer } from '../server/authserver.mjs';
const app=makeAuthServer({targetPopulation:3});
await new Promise(r=>app.http.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({args:['--use-gl=swiftshader','--enable-webgl','--no-sandbox','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1280,height:720}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route(/fonts\.(?:googleapis|gstatic)\.com/,r=>r.fulfill({contentType:'text/css',body:''}));
await page.addInitScript(()=>{window.requestAnimationFrame=()=>0;window.cancelAnimationFrame=()=>{};});
try{
 await page.goto(`http://127.0.0.1:5997/?authnet=${encodeURIComponent(`ws://127.0.0.1:${app.http.address().port}`)}`);
 await page.waitForFunction(()=>window.__game?._authNet?.ready,null,{timeout:90000,polling:50});
 assert.equal(await page.locator('#social-icons').count(),0);
 assert(await page.evaluate(()=>getComputedStyle(document.querySelector('#game-canvas')).filter.includes('blur(9px)')));
 await page.locator('#spectate-btn').click({force:true});
 await page.waitForFunction(()=>window.__game._spectating,null,{polling:50});
 await page.waitForFunction(()=>window.__game._spectatorPlayers().length>=2,null,{polling:50});
 await page.evaluate(()=>{const g=window.__game;g._updateMenuScene(.016);g.renderer.render(g.world.scene,g.menuCamera);});
 const id=await page.evaluate(()=>window.__game._authNet.client.you);
 await new Promise(r=>setTimeout(r,150));
 assert(app.room.players.get(id).spectating,'server did not accept spectator mode');
 assert(!app.room._canSimulate(app.room.players.get(id)),'spectator can fight/earn');
 const first=await page.evaluate(()=>window.__game._followId);
 await page.locator('#spectator-next').click();
 assert.notEqual(await page.evaluate(()=>window.__game._followId),first);
 assert(!await page.evaluate(()=>document.body.classList.contains('menu-blurred')));
 await page.keyboard.press('Escape');
 assert.equal((await page.locator('#spectate-btn').textContent()).trim(),'[ JOIN ]');
 assert(await page.evaluate(()=>document.body.classList.contains('menu-blurred')));
 await page.screenshot({path:'../repo-validation/spectator-menu.png'});
 await page.locator('#spectate-btn').click({force:true});
 await page.waitForFunction(()=>window.__game.state==='playing',null,{polling:50});
 await new Promise(r=>setTimeout(r,150));
 const playingId=await page.evaluate(()=>window.__game._authNet.client.you);
 assert(!app.room.players.get(playingId).spectating,'Join left the player spectating');
 assert(!await page.evaluate(()=>window.__game._spectating));
 assert.deepEqual(errors,[]);
 console.log('Spectator flow passed: menu blur, no social icons, live roster, individual follow, next player, ESC/Join and server combat exclusion.');
}catch(e){console.log(await page.evaluate(()=>({state:window.__game?.state,joining:window.__game?._joinInFlight,spectating:window.__game?._spectating,status:document.querySelector('#ml-region')?.textContent,button:getComputedStyle(document.querySelector('#spectate-btn')).pointerEvents})),errors);throw e;}finally{await browser.close();await app.close();}
